/**
 * Renders one table as a COPY block.
 * @template Row
 * @param {string} table The table name.
 * @param {Row[]} rows The rows.
 * @param {Array<Column<Row>>} columns The columns, in order.
 * @returns {string} The COPY statement with its data.
 */
function copyBlock(table, rows, columns) {
  const lines = rows.map((row) =>
    columns.map(([name, format]) => format(row[name])).join("\t"),
  );
  const names = columns.map(([name]) => name);
  return `COPY ${table} (${names.join(", ")}) FROM stdin;\n${lines.join("\n")}\n\\.\n`;
}

/**
 * Renders the sample database: the schema, then one COPY block per table.
 * @param {Shop} shop Every table.
 * @returns {string} The SQL file.
 */
export function renderSql(shop) {
  const body = [
    copyBlock("categories", shop.categories, categoryColumns),
    copyBlock("customers", shop.customers, customerColumns),
    copyBlock("products", shop.products, productColumns),
    copyBlock("coupons", shop.coupons, couponColumns),
    copyBlock("orders", shop.orders, orderColumns),
    copyBlock("order_items", shop.orderItems, orderItemColumns),
    copyBlock("payments", shop.payments, paymentColumns),
    copyBlock("shipments", shop.shipments, shipmentColumns),
    copyBlock("returns", shop.returns, returnColumns),
    copyBlock("reviews", shop.reviews, reviewColumns),
    copyBlock("support_tickets", shop.tickets, ticketColumns),
    copyBlock("subscriptions", shop.subscriptions, subscriptionColumns),
  ].join("\n");
  return `${ddl}\n${body}`;
}
